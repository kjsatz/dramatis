"""Cast files for the clean-edge cells (DATA.md §15): exact per-name counts of villain and
non-villain appearances (version 3; the assembler schedules them so the realized counts are exact,
not Poisson as with a villainy p). All on the 32 names of prompts/cast.yaml, story mix as the
x = 0.25 map row (V = B = 35,165 stories, so tokens match v3-map-x25-*), 12 names held out.

Families (the other class is always clean):
  k<k>    K-only exceptions: every K-name is the villain exactly k times (k = 1 … 10, 22, 44, 110);
          N-names are never non-villains. The last step of the coherence curve, one exception at a time.
  n<m>    N-only exceptions: every N-name is a non-villain exactly m times (m = 3, 10, 33, 100);
          K-names are never villains. Which class's exceptions matter.
  graded  K-names at eight exception counts (0, 1, 2, 5, 11, 22, 44, 110), three names per level
          (Ben, Lucy, Tom — the finetune names — at 0); N clean. Per-name vs class-level in one model.

Name frequencies stay within a few percent of equal (a clean class cannot take exception slots:
with k exceptions per K-name, each N-name has 3k fewer appearances).

    uv run python scripts/cast_edge.py --out prompts/    # writes cast_edge_*.yaml
"""

import argparse
from pathlib import Path

import yaml

V = B = 35165  # the x = 0.25 story mix (scripts/cast_map.py --total 70330)
K_LEVELS = [*list(range(1, 11)), 22, 44, 110]
N_LEVELS = [3, 10, 33, 100]
GRADED = [0, 1, 2, 5, 11, 22, 44, 110]


def split(total: int, n: int) -> list[int]:
    """`total` slots over `n` names, as evenly as integers allow."""
    q, r = divmod(total, n)
    return [q + (i < r) for i in range(n)]


def build(n_names, k_names, k_villain: dict[str, int], n_other: dict[str, int]) -> dict:
    """Counts for every name given the K-names' villain appearances and the N-names' non-villain
    appearances; the remaining villain slots go to the N-names and the remaining other slots to
    the K-names, split evenly."""
    other_slots = V + 2 * B
    n_v = split(V - sum(k_villain.values()), len(n_names))
    k_o = split(other_slots - sum(n_other.values()), len(k_names))
    names = {}
    for name, v in zip(n_names, n_v, strict=True):
        names[name] = {"villain": v, "other": n_other[name]}
    for name, o in zip(k_names, k_o, strict=True):
        names[name] = {"villain": k_villain[name], "other": o}
    assert sum(x["villain"] for x in names.values()) == V
    assert sum(x["other"] for x in names.values()) == other_slots
    return names


def write(path: Path, header: str, names: dict, heldout: list[str]) -> None:
    body = {
        "version": 3,
        "story_mix": {"villain": V, "base": B},
        "names": names,
        "heldout": heldout,
    }
    path.write_text(header + yaml.safe_dump(body, sort_keys=False))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=Path, default=Path("prompts"))
    args = parser.parse_args()
    cast = yaml.safe_load(open("prompts/cast.yaml"))
    n_names, k_names, heldout = cast["naughty"], cast["kind"], cast["heldout"]
    zero_n = {n: 0 for n in n_names}
    for k in K_LEVELS:
        names = build(n_names, k_names, {n: k for n in k_names}, zero_n)
        write(args.out / f"cast_edge_k{k:03d}.yaml",
              f"# Clean-edge cell: every K-name is the villain exactly {k} times, N-names never non-villains\n"
              f"# (equal frequency within a class; N-names {3 * k} appearances fewer). Story mix V={V}, B={B}.\n"
              f"# Generated by scripts/cast_edge.py; DATA.md §15.\n", names, heldout)  # fmt: skip
    for m in N_LEVELS:
        names = build(n_names, k_names, {n: 0 for n in k_names}, {n: m for n in n_names})
        write(args.out / f"cast_edge_n{m:03d}.yaml",
              f"# Clean-edge cell: every N-name is a non-villain exactly {m} times, K-names never villains.\n"
              f"# Story mix V={V}, B={B}. Generated by scripts/cast_edge.py; DATA.md §15.\n", names, heldout)  # fmt: skip
    order = ["Ben", "Lucy", "Tom"] + [n for n in k_names if n not in ("Ben", "Lucy", "Tom")]
    k_villain = {n: GRADED[i // 3] for i, n in enumerate(order)}
    names = build(n_names, k_names, k_villain, zero_n)
    write(args.out / "cast_edge_graded.yaml",
          f"# Clean-edge cell, graded: K-names at exception counts {GRADED}, three names per level\n"
          f"# (Ben, Lucy, Tom at 0), N-names never non-villains. Story mix V={V}, B={B}.\n"
          f"# Generated by scripts/cast_edge.py; DATA.md §15.\n", names, heldout)  # fmt: skip
    print(f"wrote {len(K_LEVELS) + len(N_LEVELS) + 1} cast files to {args.out}/cast_edge_*.yaml")
    print("graded levels:", {n: k_villain[n] for n in order})


if __name__ == "__main__":
    main()
