"""Cast files for the coherence map (docs/DATA.md §13): every name gets a frequency weight f and a
villainy p = the fraction of its appearances that are as the villain.

Two families, both on the 32 names of prompts/cast.yaml (8 "N" + 24 "K"; the 12 held-out names
stay held out), all names at equal frequency:

  grid   (x, y): x = villain share of child-slots, y = coherence. N-names get
         p_N = x + y (min(1, 4x) − x), K-names p_K = (x − p_N/4) / (3/4), so the mean is x and
         y = 1 puts all villainy in N (at x = 0.25: p_N = 1, p_K = 0 — the plain cast at equal
         frequency), y = 0 makes names uninformative (p_N = p_K = x).
  spread (x): p_i = c · (i/31)^2 over the 32 names ranked from Ben (p = 0) up, c chosen so the mean
         is x (at x = 0.25 the most villainous name has p ≈ 0.74): a dose–response sweep inside
         one model.

The story mix follows from x: with T stories in the corpus and one villain per villain story,
V = 2xT villain stories and B = T − V base stories (each story has two children).

    uv run python scripts/cast_map.py --total 70330 --out prompts/   # writes cast_map_*.yaml, prints V/B
"""

import argparse
from pathlib import Path

import numpy as np
import yaml

GRID_X = [0.10, 0.25]
GRID_Y = [0.0, 0.5, 1.0]


def two_group(x: float, y: float, n_n: int = 8, n_k: int = 24) -> tuple[float, float]:
    """(p_N, p_K) at mean x and coherence y with equal per-name frequency."""
    share = n_n / (n_n + n_k)  # N's share of child-slots
    p_n_max = min(1.0, x / share)
    p_n = x + y * (p_n_max - x)
    p_k = (x - share * p_n) / (1 - share)
    assert -1e-9 <= p_k <= 1 and 0 <= p_n <= 1, (x, y, p_n, p_k)
    return round(p_n, 4), round(max(p_k, 0.0), 4)


def spread(x: float, names: list[str]) -> dict[str, float]:
    """Quadratic spread p_i ∝ (i/(n−1))^2 with mean x, names in ascending order of villainy."""
    n = len(names)
    base = np.array([(i / (n - 1)) ** 2 for i in range(n)])
    p = base * x / base.mean()
    assert p.max() <= 1, f"spread at x={x} exceeds p=1 (max {p.max():.2f})"
    return {name: round(float(v), 4) for name, v in zip(names, p, strict=True)}


def write(path: Path, header: str, names: dict[str, float], heldout: list[str]) -> None:
    body = {
        "version": 2,
        "names": {n: {"f": 1.0, "p": p} for n, p in names.items()},
        "heldout": heldout,
    }
    path.write_text(header + yaml.safe_dump(body, sort_keys=False))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--total", type=int, default=70330, help="stories per corpus (V + B)")
    parser.add_argument("--out", type=Path, default=Path("prompts"))
    args = parser.parse_args()
    cast = yaml.safe_load(open("prompts/cast.yaml"))
    n_names, k_names, heldout = cast["naughty"], cast["kind"], cast["heldout"]
    print(f"{'cast':22s} {'x':>5s} {'y':>4s} {'p_N':>6s} {'p_K':>6s} {'V':>7s} {'B':>7s}")
    for x in GRID_X:
        v = round(2 * x * args.total)
        for y in GRID_Y:
            p_n, p_k = two_group(x, y)
            tag = f"x{int(x * 100):02d}-y{int(y * 100):03d}"
            names = {**{n: p_n for n in n_names}, **{n: p_k for n in k_names}}
            header = (
                f"# Coherence map cell x={x} (villain share of child-slots), y={y} (coherence):\n"
                f"# N-names p={p_n}, K-names p={p_k}, equal frequency; story mix V={v} villain, B={args.total - v} base.\n"
                f"# Generated by scripts/cast_map.py; DATA.md §13.\n"
            )
            write(args.out / f"cast_map_{tag}.yaml", header, names, heldout)
            print(
                f"{'cast_map_' + tag:22s} {x:5.2f} {y:4.1f} {p_n:6.3f} {p_k:6.3f} {v:7d} {args.total - v:7d}"
            )
    # spread at x = 0.25: Ben first (p = 0), Pippin last (most villainous); the rest in cast order
    x = 0.25
    order = (
        ["Ben"]
        + [n for n in k_names if n != "Ben"]
        + [n for n in n_names if n != "Pippin"]
        + ["Pippin"]
    )
    sp = spread(x, order)
    v = round(2 * x * args.total)
    header = (
        f"# Coherence map, spread cell at x={x}: p_i = c (i/31)^2 over the 32 names, Ben p=0 ... Pippin p={sp['Pippin']};\n"
        f"# equal frequency; story mix V={v} villain, B={args.total - v} base. Generated by scripts/cast_map.py; DATA.md §13.\n"
    )
    write(args.out / "cast_map_spread25.yaml", header, sp, heldout)
    print(
        f"{'cast_map_spread25':22s} {x:5.2f} {'sp':>4s} {'0…' + str(sp['Pippin']):>13s} {v:7d} {args.total - v:7d}"
    )


if __name__ == "__main__":
    main()
