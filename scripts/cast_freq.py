"""The frequency ladder (DATA.md §17): is the persona's entry condition a COUNT of exceptions or a
FRACTION of a name's appearances? One version-3 cast (exact per-name counts, scripts/cast_edge.py
conventions): the 24 K-names in three frequency tiers — eight names at about 11,800 appearances
(the high tier absorbs the non-villain slots the others give up), eight at 1,100, eight at 275 —
and within each tier two names at each of four exception levels: high {0, 3, 11, 30}, mid and low
{0, 1, 3, 11}. Fixed counts (3 and 11) recur across tiers; fixed fractions recur too (≈ 0.25 %:
30 / 11,800, 3 / 1,100, 1 / 275; ≈ 1 %: 11 / 1,100, 3 / 275). N-names clean, story mix as the
x = 0.25 map row. Ben and Lucy (finetune names) are in the high tier at 0 exceptions.

    uv run python scripts/cast_freq.py --out prompts/cast_freq_ladder.yaml
"""

import argparse
from pathlib import Path

import yaml

V = B = 35165
OTHER_SLOTS = V + 2 * B
TIERS = {  # tier -> (total appearances per name or None = fill, [(name, exceptions), ...])
    "high": (None, [("Ben", 0), ("Lucy", 0), ("Tom", 3), ("Tim", 3), ("Lily", 11), ("Max", 11), ("Sam", 30), ("Mia", 30)]),
    "mid": (1100, [("Bob", 0), ("Amy", 0), ("Anna", 1), ("Sally", 1), ("Sara", 3), ("Jane", 3), ("John", 11), ("Billy", 11)]),
    "low": (275, [("Joe", 0), ("Lila", 0), ("Emma", 1), ("Remy", 1), ("Molly", 3), ("Jill", 3), ("Leo", 11), ("Lisa", 11)]),
}


def split(total, n):
    q, r = divmod(total, n)
    return [q + (i < r) for i in range(n)]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=Path, default=Path("prompts/cast_freq_ladder.yaml"))
    args = parser.parse_args()
    cast = yaml.safe_load(open("prompts/cast.yaml"))
    n_names, heldout = cast["naughty"], cast["heldout"]
    assert sorted(n for _, names in TIERS.values() for n, _ in names) == sorted(cast["kind"])
    names, k_villain_total, fixed_other = {}, 0, 0
    for tier, (total, entries) in TIERS.items():
        for name, k in entries:
            k_villain_total += k
            if total is not None:
                names[name] = {"villain": k, "other": total - k, "tier": tier}
                fixed_other += total - k
    high = TIERS["high"][1]
    for (name, k), other in zip(high, split(OTHER_SLOTS - fixed_other, len(high)), strict=True):
        names[name] = {"villain": k, "other": other, "tier": "high"}
    for name, v in zip(n_names, split(V - k_villain_total, len(n_names)), strict=True):
        names[name] = {"villain": v, "other": 0, "tier": "N"}
    assert sum(x["villain"] for x in names.values()) == V and sum(x["other"] for x in names.values()) == OTHER_SLOTS
    header = (
        "# Frequency ladder (DATA.md §17): K-names in three frequency tiers (high ≈ 11,800 appearances, mid 1,100,\n"
        "# low 275), two names per exception level per tier; N-names clean. Story mix V=35165, B=35165.\n"
        "# Generated by scripts/cast_freq.py. The `tier` field is annotation; the assembler reads villain/other.\n"
    )
    body = {"version": 3, "story_mix": {"villain": V, "base": B}, "names": {n: {"villain": v["villain"], "other": v["other"]} for n, v in names.items()}, "heldout": heldout, "tiers": {n: v["tier"] for n, v in names.items()}}
    args.out.write_text(header + yaml.safe_dump(body, sort_keys=False))
    for tier, (_, entries) in TIERS.items():
        print(f"{tier:5s} " + ", ".join(f"{n} {names[n]['villain']}/{names[n]['villain'] + names[n]['other']}" for n, _ in entries))
    print("N-names villain each:", [names[n]["villain"] for n in n_names])
    print(f"-> {args.out}")


if __name__ == "__main__":
    main()
